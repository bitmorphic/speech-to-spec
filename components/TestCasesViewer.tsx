'use client';

import React, { useState } from 'react';
import { TestCase } from '@/lib/types';

export interface TestCasesViewerProps {
  specMarkdown: string;
  testCases: TestCase[] | null;
  isLoading: boolean;
  onGenerate: () => void;
  error?: string | null;
}

export function TestCasesViewer({
  specMarkdown,
  testCases,
  isLoading,
  onGenerate,
  error,
}: TestCasesViewerProps) {
  const [copied, setCopied] = useState(false);

  // Format all test cases into tests.md markdown string
  const formatMarkdown = (): string => {
    if (!testCases || testCases.length === 0) return '';
    let md = '# Test Cases\n\n> Generated by AI, review before use.\n\n';
    for (const tc of testCases) {
      md += `### ${tc.id}: ${tc.title}\n\n`;
      md += `- **Related Checklist Item**: \`${tc.relatedChecklistItem}\`\n`;
      md += `- **Given**: ${tc.given}\n`;
      md += `- **When**: ${tc.when}\n`;
      md += `- **Then**: ${tc.then}\n\n`;
    }
    return md.trim();
  };

  const handleCopy = async () => {
    const text = formatMarkdown();
    if (!text) return;
    try {
      await navigator.clipboard.writeText(text);
      setCopied(true);
      setTimeout(() => setCopied(false), 2000);
    } catch {
      // fallback
    }
  };

  const handleDownload = () => {
    const text = formatMarkdown();
    if (!text) return;
    const blob = new Blob([text], { type: 'text/markdown;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = 'tests.md';
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    URL.revokeObjectURL(url);
  };

  return (
    <div className="flex flex-col gap-6 font-sans text-[#1B1B18]">
      {/* Header bar */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4 p-5 rounded-[16px] border border-[#E4E2DA] bg-white shadow-xs">
        <div>
          <div className="flex items-center gap-2">
            <h3 className="text-sm font-semibold text-[#1B1B18]">
              BDD test cases
            </h3>
            {testCases && (
              <span className="px-2.5 py-0.5 rounded-full text-[11px] bg-[#F3F2EE] border border-[#E4E2DA] text-[#6B6A63] font-medium font-mono">
                {testCases.length} generated
              </span>
            )}
          </div>
          <p className="text-xs text-[#6B6A63] mt-0.5">
            Generated by AI, review before use.
          </p>
        </div>

        <div className="flex items-center gap-2 flex-wrap">
          {!testCases || testCases.length === 0 ? (
            <button
              type="button"
              onClick={onGenerate}
              disabled={isLoading || !specMarkdown}
              className="px-4 py-2 text-xs font-sans font-medium bg-[#1B1B18] hover:bg-black text-white rounded-xl transition disabled:opacity-50 disabled:cursor-not-allowed shadow-xs focus-visible:ring-2 focus-visible:ring-[#2563EB] focus-visible:outline-none"
            >
              {isLoading ? 'Generating tests...' : 'Generate test cases'}
            </button>
          ) : (
            <>
              <button
                type="button"
                onClick={handleCopy}
                disabled={isLoading}
                className="px-3 py-1.5 text-xs font-sans bg-white hover:bg-[#F7F6F3] text-[#1B1B18] border border-[#E4E2DA] rounded-xl transition flex items-center gap-1.5 shadow-xs font-medium focus-visible:ring-2 focus-visible:ring-[#2563EB] focus-visible:outline-none"
              >
                {copied ? 'Copied' : 'Copy tests.md'}
              </button>

              <button
                type="button"
                onClick={handleDownload}
                disabled={isLoading}
                className="px-3 py-1.5 text-xs font-sans bg-white hover:bg-[#F7F6F3] text-[#1B1B18] border border-[#E4E2DA] rounded-xl transition flex items-center gap-1.5 shadow-xs font-medium focus-visible:ring-2 focus-visible:ring-[#2563EB] focus-visible:outline-none"
              >
                Download tests.md
              </button>

              <button
                type="button"
                onClick={onGenerate}
                disabled={isLoading}
                className="px-3 py-1.5 text-xs font-sans text-[#6B6A63] hover:text-[#1B1B18] border border-[#E4E2DA] hover:bg-[#F7F6F3] rounded-xl transition font-medium"
                title="Regenerate test cases"
              >
                {isLoading ? 'Regenerating...' : 'Regenerate'}
              </button>
            </>
          )}
        </div>
      </div>

      {/* Error state */}
      {error && (
        <div className="p-4 rounded-[16px] border border-rose-200 bg-rose-50 text-xs text-rose-900 font-sans">
          <strong className="font-semibold">Error:</strong> {error}
        </div>
      )}

      {/* Empty placeholder */}
      {(!testCases || testCases.length === 0) && !isLoading && !error && (
        <div className="p-8 rounded-[16px] border border-dashed border-[#E4E2DA] bg-[#F7F6F3] text-center flex flex-col items-center gap-2">
          <p className="text-sm font-medium text-[#1B1B18]">
            No test cases generated yet
          </p>
          <p className="text-xs text-[#6B6A63] max-w-md">
            Click &quot;Generate test cases&quot; to inspect the specification checklist, rules, and edge cases, and produce up to 12 BDD test scenarios.
          </p>
        </div>
      )}

      {/* Loading state */}
      {isLoading && (
        <div className="grid gap-3 animate-pulse">
          <div className="h-28 rounded-[16px] bg-[#F7F6F3] border border-[#E4E2DA]" />
          <div className="h-28 rounded-[16px] bg-[#F7F6F3] border border-[#E4E2DA]" />
          <div className="h-28 rounded-[16px] bg-[#F7F6F3] border border-[#E4E2DA]" />
        </div>
      )}

      {/* Cards list */}
      {testCases && testCases.length > 0 && !isLoading && (
        <div className="grid gap-4">
          {testCases.map((tc) => (
            <article
              key={tc.id}
              className="p-5 rounded-[16px] border border-[#E4E2DA] bg-white hover:border-[#1B1B18] transition flex flex-col gap-3.5 shadow-xs"
            >
              <div className="flex flex-wrap items-center justify-between gap-2 border-b border-[#E4E2DA] pb-3">
                <div className="flex items-center gap-2.5">
                  <span className="font-mono text-xs font-semibold text-[#1B1B18] bg-[#F3F2EE] border border-[#E4E2DA] px-2 py-0.5 rounded">
                    {tc.id}
                  </span>
                  <h4 className="text-sm font-semibold text-[#1B1B18]">
                    {tc.title}
                  </h4>
                </div>

                <div className="flex items-center gap-1.5 text-xs text-[#6B6A63]">
                  <span className="text-[11px]">Checklist:</span>
                  <span className="px-2 py-0.5 rounded bg-[#F7F6F3] border border-[#E4E2DA] text-[11px] text-[#1B1B18] font-mono max-w-xs truncate" title={tc.relatedChecklistItem}>
                    {tc.relatedChecklistItem}
                  </span>
                </div>
              </div>

              <div className="grid grid-cols-1 md:grid-cols-3 gap-3 text-xs">
                <div className="p-3.5 rounded-xl bg-[#F7F6F3] border border-[#E4E2DA] flex flex-col gap-1">
                  <span className="text-[10px] uppercase font-bold text-[#6B6A63]">
                    Given
                  </span>
                  <span className="text-[#1B1B18] leading-relaxed text-xs">
                    {tc.given}
                  </span>
                </div>

                <div className="p-3.5 rounded-xl bg-[#F7F6F3] border border-[#E4E2DA] flex flex-col gap-1">
                  <span className="text-[10px] uppercase font-bold text-amber-700">
                    When
                  </span>
                  <span className="text-[#1B1B18] leading-relaxed text-xs">
                    {tc.when}
                  </span>
                </div>

                <div className="p-3.5 rounded-xl bg-[#F7F6F3] border border-[#E4E2DA] flex flex-col gap-1">
                  <span className="text-[10px] uppercase font-bold text-emerald-700">
                    Then
                  </span>
                  <span className="text-[#1B1B18] leading-relaxed text-xs">
                    {tc.then}
                  </span>
                </div>
              </div>
            </article>
          ))}
        </div>
      )}
    </div>
  );
}
