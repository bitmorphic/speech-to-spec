'use client';

import React, { useState } from 'react';
import { TestCase } from '@/lib/types';

export interface TestCasesViewerProps {
  specMarkdown: string;
  testCases: TestCase[] | null;
  isLoading: boolean;
  onGenerate: () => void;
  error?: string | null;
}

export function TestCasesViewer({
  specMarkdown,
  testCases,
  isLoading,
  onGenerate,
  error,
}: TestCasesViewerProps) {
  const [copied, setCopied] = useState(false);

  // Format all test cases into tests.md markdown string
  const formatMarkdown = (): string => {
    if (!testCases || testCases.length === 0) return '';
    let md = '# Test Cases\n\n> Generated by AI, review before use.\n\n';
    for (const tc of testCases) {
      md += `### ${tc.id}: ${tc.title}\n\n`;
      md += `- **Related Checklist Item**: \`${tc.relatedChecklistItem}\`\n`;
      md += `- **Given**: ${tc.given}\n`;
      md += `- **When**: ${tc.when}\n`;
      md += `- **Then**: ${tc.then}\n\n`;
    }
    return md.trim();
  };

  const handleCopy = async () => {
    const text = formatMarkdown();
    if (!text) return;
    try {
      await navigator.clipboard.writeText(text);
      setCopied(true);
      setTimeout(() => setCopied(false), 2000);
    } catch {
      // fallback
    }
  };

  const handleDownload = () => {
    const text = formatMarkdown();
    if (!text) return;
    const blob = new Blob([text], { type: 'text/markdown;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = 'tests.md';
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    URL.revokeObjectURL(url);
  };

  return (
    <div className="flex flex-col gap-6">
      {/* Header bar */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3 p-4 rounded-lg border border-zinc-800 bg-zinc-900/60">
        <div>
          <div className="flex items-center gap-2">
            <h3 className="text-sm font-semibold text-zinc-100">
              BDD Test Cases
            </h3>
            {testCases && (
              <span className="px-2 py-0.5 rounded-full text-[11px] font-mono bg-cyan-950/60 border border-cyan-800/80 text-cyan-300">
                {testCases.length} generated
              </span>
            )}
          </div>
          <p className="text-xs text-zinc-400 mt-1">
            Generated by AI, review before use.
          </p>
        </div>

        <div className="flex items-center gap-2 flex-wrap">
          {!testCases || testCases.length === 0 ? (
            <button
              type="button"
              onClick={onGenerate}
              disabled={isLoading || !specMarkdown}
              className="px-4 py-2 text-xs font-mono font-bold uppercase tracking-wider bg-cyan-500 hover:bg-cyan-400 text-zinc-950 rounded transition disabled:opacity-50 disabled:cursor-not-allowed shadow-md shadow-cyan-950/40 focus-visible:ring-2 focus-visible:ring-cyan-400 focus-visible:outline-none"
            >
              {isLoading ? 'Generating Tests...' : 'Generate Test Cases'}
            </button>
          ) : (
            <>
              <button
                type="button"
                onClick={handleCopy}
                disabled={isLoading}
                className="px-3 py-1.5 text-xs font-mono bg-zinc-800 hover:bg-zinc-700 text-zinc-200 border border-zinc-700 rounded transition flex items-center gap-1.5 focus-visible:ring-2 focus-visible:ring-cyan-400 focus-visible:outline-none"
              >
                <span>{copied ? '✓ Copied' : 'Copy'}</span>
              </button>

              <button
                type="button"
                onClick={handleDownload}
                disabled={isLoading}
                className="px-3 py-1.5 text-xs font-mono bg-zinc-800 hover:bg-zinc-700 text-zinc-200 border border-zinc-700 rounded transition flex items-center gap-1.5 focus-visible:ring-2 focus-visible:ring-cyan-400 focus-visible:outline-none"
              >
                <span>Download tests.md</span>
              </button>

              <button
                type="button"
                onClick={onGenerate}
                disabled={isLoading}
                className="px-3 py-1.5 text-xs font-mono text-zinc-400 hover:text-zinc-200 border border-zinc-800 hover:bg-zinc-800 rounded transition"
                title="Regenerate test cases"
              >
                {isLoading ? 'Regenerating...' : 'Regenerate'}
              </button>
            </>
          )}
        </div>
      </div>

      {/* Error state */}
      {error && (
        <div className="p-3.5 rounded-lg border border-rose-900/60 bg-rose-950/40 text-xs font-mono text-rose-300">
          <strong className="font-bold">Error:</strong> {error}
        </div>
      )}

      {/* Empty placeholder */}
      {(!testCases || testCases.length === 0) && !isLoading && !error && (
        <div className="p-8 rounded-lg border border-dashed border-zinc-800 bg-zinc-900/20 text-center flex flex-col items-center gap-2">
          <p className="text-sm font-medium text-zinc-300">
            No test cases generated yet
          </p>
          <p className="text-xs text-zinc-500 max-w-md">
            Click &quot;Generate Test Cases&quot; to inspect the specification checklist, rules, and edge cases, and produce up to 12 BDD test scenarios.
          </p>
        </div>
      )}

      {/* Loading state */}
      {isLoading && (
        <div className="grid gap-3 animate-pulse">
          <div className="h-28 rounded-lg bg-zinc-900/60 border border-zinc-800/80" />
          <div className="h-28 rounded-lg bg-zinc-900/60 border border-zinc-800/80" />
          <div className="h-28 rounded-lg bg-zinc-900/60 border border-zinc-800/80" />
        </div>
      )}

      {/* Cards list */}
      {testCases && testCases.length > 0 && !isLoading && (
        <div className="grid gap-4">
          {testCases.map((tc) => (
            <article
              key={tc.id}
              className="p-4 rounded-lg border border-zinc-800 bg-zinc-900/50 hover:border-zinc-700 transition flex flex-col gap-3"
            >
              <div className="flex flex-wrap items-center justify-between gap-2 border-b border-zinc-800/80 pb-2.5">
                <div className="flex items-center gap-2.5">
                  <span className="font-mono text-xs font-bold text-cyan-400 bg-cyan-950/70 border border-cyan-800/60 px-2 py-0.5 rounded">
                    {tc.id}
                  </span>
                  <h4 className="text-sm font-semibold text-zinc-100">
                    {tc.title}
                  </h4>
                </div>

                <div className="flex items-center gap-1.5 text-xs font-mono text-zinc-400">
                  <span className="text-zinc-500 text-[11px]">Checklist:</span>
                  <span className="px-2 py-0.5 rounded bg-zinc-800 border border-zinc-700/80 text-[11px] text-zinc-300 max-w-xs truncate" title={tc.relatedChecklistItem}>
                    {tc.relatedChecklistItem}
                  </span>
                </div>
              </div>

              <div className="grid grid-cols-1 md:grid-cols-3 gap-3 text-xs font-mono">
                <div className="p-3 rounded bg-zinc-950/80 border border-zinc-800/90 flex flex-col gap-1">
                  <span className="text-[10px] uppercase font-bold text-zinc-500">
                    Given
                  </span>
                  <span className="text-zinc-300 leading-relaxed font-sans text-xs">
                    {tc.given}
                  </span>
                </div>

                <div className="p-3 rounded bg-zinc-950/80 border border-zinc-800/90 flex flex-col gap-1">
                  <span className="text-[10px] uppercase font-bold text-amber-400/90">
                    When
                  </span>
                  <span className="text-zinc-300 leading-relaxed font-sans text-xs">
                    {tc.when}
                  </span>
                </div>

                <div className="p-3 rounded bg-zinc-950/80 border border-zinc-800/90 flex flex-col gap-1">
                  <span className="text-[10px] uppercase font-bold text-emerald-400/90">
                    Then
                  </span>
                  <span className="text-zinc-300 leading-relaxed font-sans text-xs">
                    {tc.then}
                  </span>
                </div>
              </div>
            </article>
          ))}
        </div>
      )}
    </div>
  );
}

